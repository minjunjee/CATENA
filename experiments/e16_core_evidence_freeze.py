from __future__ import annotations

from catena.core.io import write_json
from catena.eval.evidence_freeze import freeze_evidence
from experiments.common import build_parser, finalize_run, initialize_run

EXPERIMENT_ID = "e16_core_evidence_freeze"
DEFAULT_CONFIG = "configs/e16_core_evidence_freeze.yaml"


def main() -> None:
    parser = build_parser(EXPERIMENT_ID, DEFAULT_CONFIG)
    args = parser.parse_args()
    config, run_dir, _ = initialize_run(
        experiment_id=EXPERIMENT_ID,
        config_path=args.config,
        artifact_root=args.artifact_root,
        device_request=args.device,
    )
    registry = freeze_evidence(
        artifact_root=args.artifact_root,
        evidence_contract=dict(config["evidence"]),
        validate_only=bool(args.dry_run),
    )
    invalid = [
        name
        for name, item in registry["evidence"].items()
        if not item.get("valid", False)
    ]
    write_json(run_dir / "evidence_registry.json", registry)

    macros: list[str] = ["% Auto-generated by e16_core_evidence_freeze.py"]
    for name, item in sorted(registry["evidence"].items()):
        safe = "".join(character for character in name.title() if character.isalnum())
        status = str(item.get("claim_disposition", "INVALID"))
        macros.append(f"\\newcommand{{\\Result{safe}Status}}{{{status}}}")
    (run_dir / "results_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")

    complete = bool(registry["core_registry_complete"])
    report = {
        "status": "DRY_RUN" if args.dry_run else ("PASS" if complete else "FAIL"),
        "invalid_claims": invalid,
        "claim_gate": {
            "core_registry_complete": complete,
            "allowed_claim": (
                "Only frozen reports and hashes in evidence_registry.json may "
                "populate the paper."
            ),
            "forbidden_claim": "Any result absent from the frozen evidence registry.",
        },
    }
    finalize_run(
        experiment_id=EXPERIMENT_ID,
        artifact_root=args.artifact_root,
        run_dir=run_dir,
        report=report,
    )
    print(f"[{EXPERIMENT_ID}] PASS: {run_dir}")


if __name__ == "__main__":
    main()
