from __future__ import annotations

import sys
from pathlib import Path

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from catena.core.io import write_json
from catena.eval.postcore_evidence_freeze import freeze_postcore_evidence
from experiments.common import build_parser, finalize_run, initialize_run

EXPERIMENT_ID = "e17_postcore_evidence_freeze"
DEFAULT_CONFIG = "configs/e17_postcore_evidence_freeze.yaml"


def main() -> None:
    parser = build_parser(EXPERIMENT_ID, DEFAULT_CONFIG)
    parser.add_argument(
        "--evidence-root",
        default=None,
        help=(
            "Read-only source artifact root. Defaults to --artifact-root; "
            "set separately to write a dry-run outside the evidence tree."
        ),
    )
    args = parser.parse_args()
    run_mode = "DRY_RUN" if args.dry_run else "MAIN"
    config, run_dir, _ = initialize_run(
        experiment_id=EXPERIMENT_ID,
        config_path=args.config,
        artifact_root=args.artifact_root,
        device_request=args.device,
        run_mode=run_mode,
    )
    repo_root = Path(__file__).resolve().parents[1]
    registry = freeze_postcore_evidence(
        repo_root=repo_root,
        artifact_root=args.evidence_root or args.artifact_root,
        evidence_contract=dict(config["evidence"]),
        dry_run=bool(args.dry_run),
    )
    invalid = [
        name
        for name, item in registry["evidence"].items()
        if not item.get("valid", False)
    ]
    write_json(run_dir / "postcore_evidence_registry.json", registry)

    macros = ["% Auto-generated by e17_postcore_evidence_freeze.py"]
    for name, item in sorted(registry["evidence"].items()):
        safe = "".join(
            character for character in name.title() if character.isalnum()
        )
        disposition = str(item.get("claim_disposition", "INVALID"))
        macros.append(
            f"\\newcommand{{\\Postcore{safe}Status}}{{{disposition}}}"
        )
    (run_dir / "postcore_results_macros.tex").write_text(
        "\n".join(macros) + "\n",
        encoding="utf-8",
    )

    complete = bool(registry["postcore_registry_complete"])
    status = "DRY_RUN" if args.dry_run else ("PASS" if complete else "FAIL")
    report = {
        "status": status,
        "execution_status": status,
        "evidence_tier": "POSTCORE_CONTROLLED_REFERENCE_REGISTRY",
        "scientific_evidence": False,
        "invalid_records": invalid,
        "claim_gate": {
            "postcore_registry_complete": complete,
            "canonical_freeze_written": registry[
                "canonical_freeze_written"
            ],
            "original_repair_dispositions_separated": True,
            "exact_run_paths_verified": complete,
            "scope_flags_recorded": True,
            "allowed_claim": (
                "Only exact, hash-verified post-core records may be used "
                "within each record's explicit scope flags."
            ),
            "forbidden_claim": (
                "Dry/reference records as official operators, language "
                "models, natural-language transactions, or agents."
            ),
        },
    }
    finalize_run(
        experiment_id=EXPERIMENT_ID,
        artifact_root=args.artifact_root,
        run_dir=run_dir,
        report=report,
    )
    print(
        f"[{EXPERIMENT_ID}] {status}: "
        f"complete={complete} run_dir={run_dir}"
    )
    if not complete:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
