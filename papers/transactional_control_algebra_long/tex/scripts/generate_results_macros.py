#!/usr/bin/env python3
"""Generate TeX result macros from the paper's canonical Markdown table."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

TOKEN_RE = re.compile(r"^\|\s*`([A-Z0-9_]+)`\s*\|\s*([^|]+?)\s*\|$")
VALUE_RE = re.compile(r"^-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?$")


def paths() -> tuple[Path, Path]:
    tex_root = Path(__file__).resolve().parents[1]
    source = tex_root.parent / "figures" / "RESULTS_MACROS.md"
    output = tex_root / "generated" / "results_macros.tex"
    return source, output


def parse_table(source: Path) -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    for line in source.read_text(encoding="utf-8").splitlines():
        match = TOKEN_RE.match(line)
        if not match:
            continue
        token, value = match.groups()
        value = value.strip()
        if not VALUE_RE.fullmatch(value):
            raise ValueError(f"non-numeric macro value for {token}: {value!r}")
        rows.append((token, value))
    if not rows:
        raise ValueError(f"no result macros parsed from {source}")
    tokens = [token for token, _ in rows]
    if len(tokens) != len(set(tokens)):
        raise ValueError("duplicate result token in Markdown source")
    return rows


def render(source: Path, rows: list[tuple[str, str]]) -> str:
    lines = [
        "% Generated by tex/scripts/generate_results_macros.py.",
        "% Canonical source: figures/RESULTS_MACROS.md",
        "% Do not edit this file manually.",
        r"\newcommand{\CATENAResult}[1]{\csname CATENAResult@#1\endcsname}",
    ]
    for token, value in rows:
        lines.append(rf"\expandafter\def\csname CATENAResult@{token}\endcsname{{{value}}}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed generated file is missing or stale",
    )
    args = parser.parse_args()

    source, output = paths()
    expected = render(source, parse_table(source))
    if args.check:
        if not output.exists():
            print(f"missing generated macro file: {output}", file=sys.stderr)
            return 1
        if output.read_text(encoding="utf-8") != expected:
            print(f"stale generated macro file: {output}", file=sys.stderr)
            return 1
        print(f"PASS: TeX result macros match {source}")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(expected, encoding="utf-8")
    print(f"WROTE: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
